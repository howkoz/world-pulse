"""Build pulse-data.js from pulse-data.json for the World Pulse home page.

Run after every edit:  py build_pulse.py
It checks the data first (no em or en dashes, known categories and statuses, dates in order,
linked files exist) and refuses to write if anything is wrong, so the page never breaks.
"""
import json
import os
import re
import sys
from datetime import datetime, timezone

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'pulse-data.json')
OUT = os.path.join(HERE, 'pulse-data.js')
DESK = os.path.dirname(HERE)
TAGS = {'NEW', 'UPDATED', 'UNPROVEN', 'NO CHANGE', 'RESULT'}


def main():
    raw = open(SRC, encoding='utf-8').read()
    errors = []
    for bad, name in ((chr(0x2014), 'em dash'), (chr(0x2013), 'en dash')):
        if bad in raw:
            errors.append('contains an %s' % name)
    data = json.loads(raw)
    cats, stats = data['categories'], data['statuses']
    ids = set()
    for t in data['threads']:
        tid = t.get('id', '?')
        if tid in ids:
            errors.append('duplicate thread id ' + tid)
        ids.add(tid)
        for key in ('title', 'cat', 'status', 'place', 'first', 'updates'):
            if key not in t:
                errors.append('%s: missing %s' % (tid, key))
        if t.get('cat') not in cats:
            errors.append('%s: unknown category %s' % (tid, t.get('cat')))
        if t.get('status') not in stats:
            errors.append('%s: unknown status %s' % (tid, t.get('status')))
        last = ''
        for u in t.get('updates', []):
            if not re.fullmatch(r'\d{4}-\d{2}-\d{2}', u.get('ed', '')):
                errors.append('%s: bad edition date %r' % (tid, u.get('ed')))
            if u.get('ed', '') < last:
                errors.append('%s: updates out of order (oldest first)' % tid)
            last = u.get('ed', '')
            if u.get('tag') not in TAGS:
                errors.append('%s: unknown tag %s' % (tid, u.get('tag')))
            if not u.get('text'):
                errors.append('%s: empty update text' % tid)
        nxt = t.get('next')
        if nxt and nxt.get('utc'):
            datetime.strptime(nxt['utc'], '%Y-%m-%dT%H:%M:%SZ')
    for e in data['editions']:
        for label, href in e.get('links', []):
            path = os.path.normpath(os.path.join(DESK, href))
            if not href.startswith('http') and not os.path.exists(path):
                errors.append('edition %s: missing file %s' % (e['date'], href))
    if errors:
        print('NOT BUILT. Fix these first:')
        for e in errors:
            print('  -', e)
        sys.exit(1)
    data['built_utc'] = datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')
    js = '/* Built by build_pulse.py from pulse-data.json. Do not edit this file by hand. */\nwindow.PULSE = ' + \
        json.dumps(data, ensure_ascii=False, indent=1) + ';\n'
    open(OUT, 'w', encoding='utf-8').write(js)
    n_up = sum(len(t['updates']) for t in data['threads'])
    print('Built pulse-data.js: %d threads, %d updates, %d editions' % (len(data['threads']), n_up, len(data['editions'])))


if __name__ == '__main__':
    main()
